def lookup() -> dict[tuple[str, str], int]:
    """(kind, GDELT code) -> UCDP country id."""
    out = {}
    for country_id, (fips, cameo) in GDELT.items():
        for code in fips:
            out[("where", code)] = country_id
        for code in cameo:
            out[("actor", code)] = country_id
            out[("target", code)] = country_id
    return out
